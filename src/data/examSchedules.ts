// 날짜별 이벤트 그룹핑 헬퍼 함수
export function getEventsByDate(date: string): ExamEvent[] {
  return examSchedules.filter((event) => event.date === date);
}

// 월별 이벤트 필터링 헬퍼 함수
export function getEventsByMonth(year: number, month: number): ExamEvent[] {
  const monthStr = `${year}-${String(month).padStart(2, "0")}`;
  return examSchedules.filter((event) => event.date.startsWith(monthStr));
}

// 자격증 ID로 이벤트 필터링 헬퍼 함수
export function getEventsByCertificationId(certId: string): ExamEvent[] {
  return examSchedules
    .filter((event) => event.certificationId === certId)
    .sort((a, b) => a.date.localeCompare(b.date));
}
